fig, ax = plt.subplots(figsize=(14, 8.75)); ax.set_xlim(0, 14); ax.set_ylim(0, 8.75); ax.axis("off")
def caja(x, y, w, h, titulo, texto, color, borde):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.12", fc=color, ec=borde, lw=1.6))
    ax.text(x + w/2, y + h - 0.22, titulo, ha="center", va="top", fontsize=10.5, weight="bold", color="#111")
    ax.text(x + w/2, y + h - 0.58, texto, ha="center", va="top", fontsize=8.3, color="#333", linespacing=1.35)
def flecha(a, b, texto="", color="#555", estilo="-|>", rad=0.0, dx=0, dy=0):
    ax.add_patch(FancyArrowPatch(a, b, arrowstyle=estilo, mutation_scale=14, color=color, lw=1.4, connectionstyle=f"arc3,rad={rad}"))
    if texto: ax.text((a[0]+b[0])/2 + dx, (a[1]+b[1])/2 + dy, texto, fontsize=7.8, color=color, ha="center", style="italic",
                      bbox=dict(fc="white", ec="none", pad=0.6))
